namespace DisasterPlus.Game
{
    /// <summary>
    /// ポーズ中も <see cref="IDisasterFeature.OnSimulationTick"/> を受け取りたい機能に付ける印。
    ///
    /// なぜ要るか（全体レビュー指摘）: <see cref="FeatureHost.SimulationTick"/> は
    /// ゲーム内経過が 0 分のとき OnSimulationTick を呼ばずに戻る。そしてロード直後の
    /// 最初の tick は必ず 0 分になるので、ロードしてすぐポーズしたままだと
    /// **天気予報パネルは全行が「読み取れません」のまま**になる。実際には何も
    /// 壊れていないのに壊れて見える、という本プロジェクトが最も嫌う形の出力だった。
    /// FeatureHost は同じ理由で「ポーズ中も診断の収集は続ける」という判断を既にしており
    /// （そちらのコメント参照）、表示専用の機能にも同じ扱いを与える。
    ///
    /// **この印を付けてよいのは、ゲームの状態を進めない「読んで表示するだけ」の機能に限る。**
    /// ポーズガードが本来守っているのは「経過 0 分でシミュレーション状態を進めない」ことで、
    /// そこは変えていない。火災旋風のように寿命・延焼・生成を進める機能には付けないこと
    /// （付けるとポーズ中に災害が進行する）。
    ///
    /// この経路で呼ばれるとき deltaMinutes は必ず 0f になる。実装側は
    /// deltaMinutes を状態の前進に使っていないことを自分で保証すること。
    ///
    /// メンバーを持たない印だけのインターフェースにしているのは、
    /// <see cref="IDisasterFeature"/> 側にメンバーを足すと、この扱いを必要としない
    /// 既存・将来の全機能に実装義務が波及するため。
    /// </summary>
    public interface IPausedTickFeature
    {
    }
}
